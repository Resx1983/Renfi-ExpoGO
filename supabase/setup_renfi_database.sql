    LEFT JOIN public."Rol" r ON u."IdRol" = r."IdRol"
    ORDER BY u."NumeroDocumento" ASC;
END;
$$;

-- Registrar usuario (retorna NumeroDocumento generado)
CREATE OR REPLACE FUNCTION public."SP_RegistrarUsuario"(
    "p_IdRol" INT DEFAULT 2,
    "p_NombreUsuario" VARCHAR(300) DEFAULT '',
    "p_ApellidoUsuario" VARCHAR(300) DEFAULT '',
    "p_Telefono" VARCHAR(100) DEFAULT NULL,
    "p_Correo" VARCHAR(300) DEFAULT '',
    "p_Contrasena" VARCHAR(300) DEFAULT '',
    "p_Estado" VARCHAR(150) DEFAULT 'Activo'
)
RETURNS INT
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_id INT;
BEGIN
    INSERT INTO public."Usuario" (
        "IdRol", "NombreUsuario", "ApellidoUsuario", "Telefono", "Correo", "Contrasena", "Estado"
    ) VALUES (
        COALESCE("p_IdRol", 2), 
        "p_NombreUsuario", 
        "p_ApellidoUsuario", 
        "p_Telefono", 
        LOWER(TRIM("p_Correo")), 
        "p_Contrasena", 
        COALESCE("p_Estado", 'Activo')
    )
    RETURNING "NumeroDocumento" INTO v_id;
    RETURN v_id;
END;
$$;

-- Iniciar sesión
CREATE OR REPLACE FUNCTION public."SP_IniciarSesion"(
    "p_Correo" VARCHAR(500),
    "p_Contrasena" VARCHAR(300)
)
RETURNS TABLE (
    "NumeroDocumento" INT,
    "IdRol" INT,
    "NombreUsuario" VARCHAR(300),
    "ApellidoUsuario" VARCHAR(300),
    "Telefono" VARCHAR(100),
    "Correo" VARCHAR(500),
    "Estado" VARCHAR(150),
    "NombreRol" VARCHAR(300)
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    RETURN QUERY
    SELECT 
        u."NumeroDocumento",
        u."IdRol",
        u."NombreUsuario",
        u."ApellidoUsuario",
        u."Telefono",
        u."Correo",
        u."Estado",
        COALESCE(r."NombreRol", 'Cliente') AS "NombreRol"
    FROM public."Usuario" u
    LEFT JOIN public."Rol" r ON u."IdRol" = r."IdRol"
    WHERE LOWER(TRIM(u."Correo")) = LOWER(TRIM("p_Correo"))
      AND u."Contrasena" = "p_Contrasena"
      AND u."Estado" = 'Activo';
END;
$$;

