CREATE OR REPLACE FUNCTION public."SP_ListarUsuarios"()
RETURNS TABLE (
    "NumeroDocumento" INT,
    "NombreUsuario" VARCHAR(300),
    "ApellidoUsuario" VARCHAR(300),
    "Telefono" VARCHAR(100),
    "Correo" VARCHAR(500),
    "Contrasena" VARCHAR(300),
    "Estado" VARCHAR(150),
    "IdRol" INT,
    "NombreRol" VARCHAR(300)
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    RETURN QUERY
    SELECT 
        u."NumeroDocumento",
        u."NombreUsuario",
        u."ApellidoUsuario",
        u."Telefono",
        u."Correo",
        u."Contrasena",
        u."Estado",
        r."IdRol",
        COALESCE(r."NombreRol", 'Sin Rol')
