CREATE OR REPLACE FUNCTION public."SP_CrearReserva"(
    "p_IdFinca" INT,
    "p_NumeroDocumentoUsuario" INT,
    "p_FechaEntrada" TIMESTAMP WITHOUT TIME ZONE,
    "p_FechaSalida" TIMESTAMP WITHOUT TIME ZONE,
    "p_MontoReserva" INT,
    "p_IdMetodoDePago" INT DEFAULT 1,
    "p_Estado" VARCHAR(150) DEFAULT 'Confirmada'
)
RETURNS INT
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_id_reserva INT;
    v_id_factura INT;
BEGIN
    INSERT INTO public."Reserva" (
        "IdFinca", "NumeroDocumentoUsuario", "FechaEntrada", "FechaSalida", "Estado", "MontoReserva"
    ) VALUES (
        "p_IdFinca", "p_NumeroDocumentoUsuario", "p_FechaEntrada", "p_FechaSalida", 
        COALESCE("p_Estado", 'Confirmada'), "p_MontoReserva"
    )
    RETURNING "IdReserva" INTO v_id_reserva;

    INSERT INTO public."Factura" ("IdReserva", "Total")
    VALUES (v_id_reserva, "p_MontoReserva")
    RETURNING "IdFactura" INTO v_id_factura;

    INSERT INTO public."Pago" ("IdFactura", "IdMetodoDePago", "Monto", "EstadoPago")
    VALUES (v_id_factura, COALESCE("p_IdMetodoDePago", 1), "p_MontoReserva", 'Pagado');

    RETURN v_id_reserva;
END;
$$;

